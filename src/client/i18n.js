export const LOCALES = { en, uk };

let current = 'en';

export function setLocale(lang) {
  current = LOCALES[lang] ? lang : 'en';
}

export function getLocale() {
  return current;
}

function interpolate(str, params) {
  if (!params) return str;
  let out = str;
  for (const [k, v] of Object.entries(params)) {
    out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}

export function t(key, params) {
  const str = LOCALES[current][key] ?? en[key] ?? key;
  return interpolate(str, params);
}

// CLDR-ish plural category for the supported locales.
// uk: 1/21/31→one, 2-4/22-24→few (except 12-14), rest→many. en: 1→one, rest→many.
function pluralForm(lang, n) {
  if (lang === 'uk') {
    const m10 = n % 10, m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return 'one';
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'few';
    return 'many';
  }
  return n === 1 ? 'one' : 'many';
}

// Plural-aware lookup: `${key}.one|few|many` in current locale (missing form
// falls back to .many → .one), then the same chain in English.
export function tc(key, n, params) {
  const resolve = (map, lang) => {
    const form = pluralForm(lang, n);
    return map[`${key}.${form}`] ?? map[`${key}.many`] ?? map[`${key}.one`];
  };
  const str = resolve(LOCALES[current], current) ?? resolve(en, 'en') ?? key;
  return interpolate(str, { n, ...params });
}
